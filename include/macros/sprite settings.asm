; --------------------------------------------------------------
; spritePosX
; --------------------------------------------------------------

spritePosX: macro position
	
	move.w	#position, aX(a1)
    endm
	
; --------------------------------------------------------------
; spritePosY
; --------------------------------------------------------------

spritePosY: macro position
	
	move.w	#position, aY(a1)
    endm
		
; --------------------------------------------------------------
; spriteDraw
; --------------------------------------------------------------

spriteDraw: macro draw
	
	move.b	#draw, aDrawFlags(a1)
    endm

; --------------------------------------------------------------
; spriteTable
; --------------------------------------------------------------

spriteTable: macro entry
	
	move.b	#(entry - Sprite_Mappings_Table)/4, aMappings(a1)
    endm
	
; --------------------------------------------------------------
; spriteFrame
; --------------------------------------------------------------

spriteFrame: macro entry
	
	move.b	#entry, aFrame(a1)
    endm
	
; --------------------------------------------------------------
; spriteAnim
; --------------------------------------------------------------

spriteAnim: macro animations
	
	move.l	#animations, aAnim(a1)
    endm

; --------------------------------------------------------------
; spriteAnimFrame
; --------------------------------------------------------------

spriteAnimFrame: macro pause, entry
		
	dc.b 	pause	
	dc.b	entry
    endm
	
; --------------------------------------------------------------
; spriteAnimEnd
; --------------------------------------------------------------

spriteAnimEnd: macro 
	
	dc.b	$FE
	even
    endm
	
; --------------------------------------------------------------
; spriteAnimLoop
; --------------------------------------------------------------

spriteAnimLoop: macro entry
	
	dc.b	$FF
	even
	dc.l 	entry
    endm
	
; --------------------------------------------------------------